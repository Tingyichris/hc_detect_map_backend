"""Seed a dev DB with an active map + plate classes so server/frontend have something to load.

    HCDMAP_DB_URL=sqlite:///./dev.db python scripts/seed_dev.py

Camera ids match server/sim/scenarios/*.yaml so `fake_pi` events line up with the map.
"""
from __future__ import annotations

from hcdmap_backend.db import SessionLocal, engine
from hcdmap_backend.models import Base, MapVersion, PlateClass
from hcdmap_backend.settings import settings

# Stadium-shaped conveyor loop in a 1600x900 canvas (loop length ~3150 px).
#
# The previous seed used only the 4 corners of a rectangle and derived camera points by
# walking the straight polygon perimeter. That was wrong: the track is rendered as a
# Catmull-Rom spline, which overshoots a sparse control polygon badly — the curve bulged out
# to x:50..1550 / y:75..825 (outside the 1600x900 canvas) and every camera point sat 8-135 px
# off the actual track, so the editor rightly refused to re-save the seed map.
#
# Fix: straight runs get several collinear control points (Catmull-Rom through collinear
# points stays straight), the ends get points around an arc, and the camera coordinates below
# were generated by sampling the *densified spline* by arc-length with the canonical
# implementation in server/src/hcdmap_server/map/geometry.py. They are literals on purpose —
# re-deriving them here would mean a third copy of the geometry to keep in sync.
# Every point below is within 0.05 px of the densified curve.
TRACK_PX = [
    [420, 190], [610, 190], [800, 190], [990, 190], [1180, 190],
    [1310, 225], [1405, 320], [1440, 450], [1405, 580], [1310, 675],
    [1180, 710], [990, 710], [800, 710], [610, 710], [420, 710],
    [290, 675], [195, 580], [160, 450], [195, 320], [290, 225],
]

# id, role, table_id, counting_point_px, view_span_px  (span[0] = upstream edge)
CAMS = [
    ("cam_kitchen", "source", None,
     [482.9, 187.4], [[388.7, 193.9], [577.4, 189.6]]),
    ("cam_t01", "table", "T01",
     [797.9, 190.0], [[703.4, 190.0], [892.5, 190.0]]),
    ("cam_t02", "table", "T02",
     [1113.0, 187.4], [[1018.5, 189.7], [1207.2, 193.3]]),
    ("cam_t03", "table", "T03",
     [1437.6, 416.6], [[1408.9, 327.0], [1432.4, 510.3]]),
    ("cam_t04", "table", "T04",
     [1022.6, 710.4], [[1117.1, 712.6], [928.1, 710.0]]),
    ("cam_t05", "table", "T05",
     [613.0, 710.0], [[707.5, 710.0], [518.5, 712.0]]),
    ("cam_t06", "table", "T06",
     [207.8, 599.7], [[275.0, 665.5], [168.6, 514.3]]),
]

CLASSES = [
    ("red", 40, "#e0564c"),
    ("gold", 80, "#e0a94c"),
    ("black", 120, "#2f333d"),
    ("green", 60, "#4cae7a"),
]


def main() -> None:
    Base.metadata.create_all(engine)
    db = SessionLocal()
    store = settings.store_id

    maps = db.query(MapVersion).filter(MapVersion.store_id == store).count()
    classes = db.query(PlateClass).filter(PlateClass.store_id == store).count()

    if maps == 0:
        cameras = []
        for cid, role, table_id, counting_px, span_px in CAMS:
            cameras.append(
                {
                    "id": cid,
                    "role": role,
                    **({"table_id": table_id} if table_id else {}),
                    "counting_point_px": counting_px,
                    "view_span_px": span_px,
                }
            )

        doc = {
            "floorplan": {"image_id": "fp_dev", "width_px": 1600, "height_px": 900},
            "track": {
                "path_px": [list(p) for p in TRACK_PX],
                "closed": True,
                "approx_loop_seconds": 108,
            },
            "cameras": cameras,
        }
        db.add(MapVersion(store_id=store, version=1, active=True, floorplan_image_id="fp_dev",
                          doc=doc, author="seed"))
    if classes == 0:
        for name, price, color in CLASSES:
            db.add(PlateClass(store_id=store, name=name, price=price, color=color))
    db.commit()
    print(
        f"seed_dev: maps={'kept' if maps else 'seeded v1'}; "
        f"plate_classes={'kept' if classes else f'seeded {len(CLASSES)}'}; store={store}"
    )


if __name__ == "__main__":
    main()
